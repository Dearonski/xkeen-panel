package xkeen

import (
	"fmt"
	"os"
	"os/exec"
	"strings"
)

// Keenetic re-runs netfilter.d hooks after every firewall rebuild, so the rules outlive both reloads and reboots
const killSwitchPath = "/opt/etc/ndm/netfilter.d/99-xkeen-panel-lock.sh"

const killSwitchChain = "XKEEN_PANEL_LOCK"

var killSwitchFamilies = []string{"iptables", "ip6tables"}

func killSwitchIPs(sites []Site) (v4, v6 []string) {
	for _, site := range sites {
		if site.Lock == nil {
			continue
		}
		for _, ip := range site.IPs {
			if strings.Contains(ip, ":") {
				v6 = append(v6, ip)
			} else {
				v4 = append(v4, ip)
			}
		}
	}
	return v4, v6
}

func killSwitchScript(v4, v6 []string) string {
	return fmt.Sprintf(`#!/bin/sh
# Generated by xkeen-panel: intercepted traffic never reaches FORWARD, so this only catches what XKeen lets go direct, e.g. mid-restart
[ "$table" = "filter" ] || exit 0
case "$type" in
	iptables) nets=%q ;;
	ip6tables) nets=%q ;;
	*) exit 0 ;;
esac
command -v "$type" >/dev/null 2>&1 || exit 0
"$type" -w -N %[3]s 2>/dev/null
"$type" -w -F %[3]s
for net in $nets; do
	"$type" -w -A %[3]s -d "$net" -j REJECT
done
"$type" -w -C FORWARD -j %[3]s 2>/dev/null || "$type" -w -I FORWARD 1 -j %[3]s
`, strings.Join(v4, " "), strings.Join(v6, " "), killSwitchChain)
}

func (m *SiteManager) syncKillSwitch(sites []Site) error {
	path := m.detector.path(killSwitchPath)
	v4, v6 := killSwitchIPs(sites)

	if len(v4)+len(v6) == 0 {
		if _, err := os.Stat(path); os.IsNotExist(err) {
			return nil
		}
		if err := os.Remove(path); err != nil {
			return err
		}
		for _, family := range killSwitchFamilies {
			if _, err := exec.LookPath(family); err != nil {
				continue
			}
			exec.Command(family, "-w", "-D", "FORWARD", "-j", killSwitchChain).Run()
			exec.Command(family, "-w", "-F", killSwitchChain).Run()
			exec.Command(family, "-w", "-X", killSwitchChain).Run()
		}
		return nil
	}

	script := killSwitchScript(v4, v6)
	if current, err := os.ReadFile(path); err != nil || string(current) != script {
		if err := writeFileAtomic(path, []byte(script), 0755); err != nil {
			return fmt.Errorf("не удалось записать %s: %w", path, err)
		}
	}

	for _, family := range killSwitchFamilies {
		if _, err := exec.LookPath(family); err != nil {
			continue
		}
		cmd := exec.Command("sh", path)
		cmd.Env = append(os.Environ(), "type="+family, "table=filter")
		if out, err := cmd.CombinedOutput(); err != nil {
			return fmt.Errorf("%s: %v %s", family, err, TailLines(string(out), 2))
		}
	}
	return nil
}
